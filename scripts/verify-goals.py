"""V7 real API/browser checks. Services must already be running on localhost.
Only accounts/goals generated by this invocation are removed. Never resets user data.
"""
from pathlib import Path
import concurrent.futures
import importlib.util
import json
import os
import re
import secrets
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("auth", ROOT / "scripts/verify-local.py")
a = importlib.util.module_from_spec(spec)
spec.loader.exec_module(a)
prefix = "goal_check_" + secrets.token_hex(5)
checks, users, tokens = [], [], []
work = ROOT / ".local/goals-verification"
work.mkdir(parents=True, exist_ok=True)


def call(label, path, method="GET", body=None, token=None, code=200):
    response = a.request(path, method, body, token)[1]
    assert response.get("code") == code, (label, response)
    checks.append(label)
    print("PASS", label, flush=True)
    return response


def main():
    config = (ROOT / "config/application-local.yml").read_text(encoding="utf-8-sig")
    password = lambda name: re.search(r"^\s{4}" + name + r":\s*(.*?)\s*$", config, re.M).group(1).strip("\"'")
    a.clear_our_rate_limits()
    admin = call("administrator login", "/empLogin", "POST", {"username": "admin01", "password": password("admin01")})["token"]
    tokens.append(admin)
    actors = {}
    for name, role in [("student", 10), ("other", 10), ("mentor", 20)]:
        pwd = secrets.token_urlsafe(18)
        username = prefix + name
        uid = call("create " + name, "/system/user", "POST", {"userName": username, "nickName": "Goal test " + name, "password": pwd, "roleId": role}, admin)["data"]
        users.append(uid)
        path = "/client/login" if role == 10 else "/empLogin"
        token = call("login " + name, path, "POST", {"username": username, "password": pwd})["token"]
        tokens.append(token)
        actors[name] = {"id": uid, "username": username, "password": pwd, "token": token}
    s, other = actors["student"]["token"], actors["other"]["token"]
    base = "/client/goals"
    assert a.sql("SELECT GROUP_CONCAT(version ORDER BY installed_rank) FROM flyway_schema_history WHERE success=1 AND version IS NOT NULL;").split(",")[:7] == [str(i) for i in range(1, 8)]
    checks.append("Flyway V1-V7 applied successfully")
    call("anonymous rejected", base, code=401)
    for name, token in [("administrator", admin), ("mentor", actors["mentor"]["token"])]:
        for method, path, body in [("GET", base, None), ("POST", base, {"title": "No"}), ("PUT", base + "/1", {"title": "No", "version": 0}), ("PUT", base + "/1/completion", {"version": 0, "completed": True}), ("DELETE", base + "/1?version=0", None)]:
            call(name + " channel denied " + method + path, path, method, body, token, 401)
    assert call("fresh student has empty list", base, token=s)["total"] == 0
    call("blank title rejected", base, "POST", {"title": "   "}, s, 400)
    call("long title rejected", base, "POST", {"title": "a" * 151}, s, 400)
    call("long notes rejected", base, "POST", {"title": "Step", "details": "x" * 2001}, s, 400)
    call("invalid status rejected", base + "?status=INVALID", token=s, code=400)
    gid = call("create ignores forged owner/status", base, "POST", {"title": "  Learn at my pace 🌱 学习一步  ", "details": "A small step", "studentId": actors["other"]["id"], "status": "COMPLETED"}, s)["data"]
    path = base + "/" + str(gid)
    goal = call("read persisted goal", path, token=s)["data"]
    assert goal["title"] == "Learn at my pace 🌱 学习一步" and goal["status"] == "ACTIVE" and goal["version"] == 0
    assert "studentId" not in goal
    assert call("spoofed list owner ignored", base + "?studentId=" + str(actors["student"]["id"]), token=other)["total"] == 0
    for label, method, url, body in [("read", "GET", path, None), ("edit", "PUT", path, {"title": "Not mine", "version": 0}), ("complete", "PUT", path + "/completion", {"version": 0, "completed": True}), ("delete", "DELETE", path + "?version=0", None)]:
        call("other student cannot " + label, url, method, body, other, 404)
    call("edit requires version", path, "PUT", {"title": "Step"}, s, 400)
    call("completion requires boolean", path + "/completion", "PUT", {"version": 0}, s, 400)
    call("delete requires version", path, "DELETE", token=s, code=400)
    with concurrent.futures.ThreadPoolExecutor(2) as pool:
        results = list(pool.map(lambda title: a.request(path, "PUT", {"title": title, "details": "Edited", "version": 0}, s)[1]["code"], ["Concurrent step A", "Concurrent step B"]))
    assert sorted(results) == [200, 409], results
    checks.append("concurrent edit: exactly one winner, no lost update")
    call("stale completion rejected", path + "/completion", "PUT", {"version": 0, "completed": True}, s, 409)
    call("mark complete", path + "/completion", "PUT", {"version": 1, "completed": True}, s)
    goal = call("completion persisted", path, token=s)["data"]
    assert goal["status"] == "COMPLETED" and goal["completedAt"]
    when = goal["completedAt"]
    call("repeat completion with current version", path + "/completion", "PUT", {"version": 2, "completed": True}, s)
    assert call("completion time preserved", path, token=s)["data"]["completedAt"] == when
    call("edit completed goal preserves status", path, "PUT", {"title": "Completed step", "details": "<img src=x onerror=alert(1)>", "version": 3}, s)
    assert call("completed filter", base + "?status=COMPLETED", token=s)["total"] == 1
    call("reopen accidental completion", path + "/completion", "PUT", {"version": 4, "completed": False}, s)
    goal = call("active state persisted", path, token=s)["data"]
    assert goal["status"] == "ACTIVE" and goal["completedAt"] is None
    call("stale delete rejected", path + "?version=4", "DELETE", token=s, code=409)
    for i in range(11):
        call("pagination goal " + str(i), base, "POST", {"title": "Small step " + str(i)}, s)
    first = call("pagination first page", base + "?current=1&pageSize=10", token=s)
    second = call("pagination second page", base + "?current=2&pageSize=10", token=s)
    assert first["total"] == second["total"] == 12 and len(first["rows"]) == 10 and len(second["rows"]) == 2
    assert not ({g["id"] for g in first["rows"]} & {g["id"] for g in second["rows"]})
    call("delete own goal", path + "?version=5", "DELETE", token=s)
    call("deleted goal unavailable", path, token=s, code=404)
    # Browser fixtures start empty; only this invocation's disposable data is removed.
    a.sql("DELETE FROM personal_goal WHERE student_id=" + str(actors["student"]["id"]))
    if "--browser" in sys.argv:
        env = os.environ.copy()
        tools = json.loads((ROOT / ".local/development-tools.json").read_text(encoding="utf-8-sig"))
        runtime = tools["nodeHome"]
        env["PATH"] = runtime + os.pathsep + env.get("PATH", "")
        for key, name in [("STUDENT", "student"), ("OTHER", "other"), ("MENTOR", "mentor")]:
            env["UPSELF_GOAL_" + key] = actors[name]["username"]
            env["UPSELF_GOAL_" + key + "_PASSWORD"] = actors[name]["password"]
        env["UPSELF_GOAL_ADMIN_PASSWORD"] = password("admin01")
        env["UPSELF_GOAL_WORK"] = str(work)
        env["UPSELF_GOAL_ID"] = str(call("browser private fixture", base, "POST", {"title": "Private goal from student A"}, s)["data"])
        with (work / "browser.log").open("w", encoding="utf-8") as log:
            result = subprocess.run([str(Path(runtime) / "node.exe"), str(ROOT / "frontend/node_modules/@playwright/test/cli.js"), "test", "goals.spec.ts"], cwd=ROOT / "frontend", env=env, stdout=log, stderr=subprocess.STDOUT)
        print((work / "browser.log").read_text(encoding="utf-8").encode("ascii", errors="backslashreplace").decode("ascii"), flush=True)
        assert result.returncode == 0, "Browser checks failed; see .local/goals-verification/browser.log"
    (work / "api-result.json").write_text(json.dumps({"passed": len(checks), "checks": checks}, indent=2), encoding="utf-8")
    print("TOTAL", len(checks), "API checks passed", flush=True)


try:
    main()
finally:
    for uid in users:
        uid = int(uid)
        if a.sql("SELECT COUNT(*) FROM sys_user WHERE id=" + str(uid) + " AND user_name LIKE '" + prefix + "%'") == "1":
            a.sql("DELETE FROM personal_goal WHERE student_id=" + str(uid) + ";DELETE FROM sys_user WHERE id=" + str(uid) + ";")
    for token in tokens:
        a.redis("DEL", a.key_for(token))
